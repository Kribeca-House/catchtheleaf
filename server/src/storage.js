import { mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { join, dirname, resolve, sep } from 'node:path';
import { S3Client, PutObjectCommand, DeleteObjectCommand } from '@aws-sdk/client-s3';

// Two backends with the same tiny interface:
//  - local disk (development): files under MEDIA_DIR, served by the app at /media/<key>
//  - S3-compatible Object Storage (Scaleway in production): served straight from the bucket,
//    so image traffic never wakes the serverless container.
const useS3 = Boolean(process.env.S3_BUCKET);
const MEDIA_DIR = resolve(process.env.MEDIA_DIR || join(process.cwd(), 'media'));

const s3 = useS3
  ? new S3Client({
      region: process.env.S3_REGION || 'fr-par',
      endpoint: process.env.S3_ENDPOINT || 'https://s3.fr-par.scw.cloud',
      credentials: { accessKeyId: process.env.S3_ACCESS_KEY, secretAccessKey: process.env.S3_SECRET_KEY },
    })
  : null;

// Keys are generated by the server (uuid + fixed extension), never taken from the client.
function localPath(key) {
  const p = resolve(MEDIA_DIR, key);
  if (!p.startsWith(MEDIA_DIR + sep)) throw new Error('bad media key');
  return p;
}

export async function put(key, bytes, contentType) {
  if (useS3) {
    await s3.send(new PutObjectCommand({
      Bucket: process.env.S3_BUCKET, Key: key, Body: bytes, ContentType: contentType,
      ACL: 'public-read', CacheControl: 'public, max-age=31536000, immutable',
    }));
  } else {
    const path = localPath(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes);
  }
}

export async function removeObject(key) {
  if (!key) return;
  try {
    if (useS3) await s3.send(new DeleteObjectCommand({ Bucket: process.env.S3_BUCKET, Key: key }));
    else await rm(localPath(key), { force: true });
  } catch { /* best effort */ }
}

export async function readLocal(key) {
  if (useS3) return null;
  try { return await readFile(localPath(key)); } catch { return null; }
}

export function url(key) {
  if (!key) return null;
  if (useS3) {
    const base = process.env.MEDIA_PUBLIC_URL || `https://${process.env.S3_BUCKET}.s3.${process.env.S3_REGION || 'fr-par'}.scw.cloud`;
    return `${base}/${key}`;
  }
  return `/media/${key}`;
}
